// Generador de registros pormenorizados de patrullajes vinculados a los campos exactos de base de datos
export function generatePlanesPatrullajesRecords(): PatrullajeRecordItem[] {
  const items: PatrullajeRecordItem[] = [];
  let counter = 1;

  for (const plan of PLANES_OPERATIVOS_CATALOGO) {
    const totalPlan = plan.patrullajesTotal;
    const puntos = plan.puntosCriticos;

    // Distribuir los patrullajes reales en los puntos del plan
    let allocated = 0;
    puntos.forEach((p, pIdx) => {
      // Tomamos la frecuencia específica si suma o ajustamos el último
      const targetCount = pIdx === puntos.length - 1 ? (totalPlan - allocated) : p.frecuenciaPatrullajes;
      allocated += targetCount;

      for (let i = 0; i < targetCount; i++) {
        // Generar fecha entre Ene 2023 y Ago 2026
        const anio = 2023 + (counter % 4); // 2023, 2024, 2025, 2026
        const mesNum = 1 + ((counter * 7) % (anio === 2026 ? 8 : 12)); // Hasta Agosto en 2026
        const diaNum = 1 + ((counter * 13) % 28);
        const fecha = `${anio}-${String(mesNum).padStart(2, '0')}-${String(diaNum).padStart(2, '0')}`;

        const hourOffset = i % 3;
        let hour = 18;
        if (p.turnoPredominante === 'MAÑANA') hour = 7 + hourOffset;
        else if (p.turnoPredominante === 'TARDE') hour = 15 + hourOffset;
        else hour = (22 + hourOffset) % 24;

        const hora = `${String(hour).padStart(2, '0')}:${String((counter * 11) % 60).padStart(2, '0')}`;
        const id = `PATR-${anio}-${String(counter).padStart(5, '0')}`;

        // REGLA OPERATIVA ESTRICTA: Las motos solo operan en turnos Mañana y Tarde (07:00 a 22:00).
        // En Turno Nocturno (22:00 a 07:00 / Madrugada) ÚNICAMENTE operan Camionetas 4x4.
        const isNight = p.turnoPredominante === 'NOCHE' || hour >= 22 || hour < 7;
        const unidadTipo = (!isNight && counter % 3 === 0)
          ? 'MOTO RÁPIDA ' + String(1 + (counter % 12)).padStart(2, '0')
          : 'MÓVIL CAMIONETA ' + String(1 + (counter % 24)).padStart(2, '0');

        items.push({
          id,
          fecha,
          anio,
          planId: plan.id,
          planNombre: plan.nombre,
          unidad: unidadTipo,
          lugar: p.lugar,
          columna1: p.columna1,
          sector: p.sector,
          zona: p.zona,
          comisaria: p.comisaria,
          turno: p.turnoPredominante,
          hora,
          observacion: `${plan.nombreCorto}: ${p.observacion}`,
          integrado: 'SI',
          agente: '', // Campo editable vacío por defecto para ingreso manual
          tipoEspacio: p.tipoEspacio,
        });

        counter++;
      }
    });
  }

  return items;
}
